function buildEvents() {
  const rows = [];      /* 逐条抽取结果，给明细页用 */
  const map = new Map();

  INPUT.slice().sort(sortByTime).forEach(it => {
    /* 主体抽不到也不丢：拿标题片段单列一条，宁可多一条线，也不把两家并成一家。
       跟踪的价值在于不漏，抽得糙可以事后补实体库，漏掉就没了。 */
    const subj = pickSubject(it.title)
      || { n: it.title.replace(/[，。、：；（）]/g, ' ').slice(0, 8), label: '', role: '其他', a: [], temp: true };
    const type = pickType(it);
    const row = { it, subj, type, stage: null, key: null, reason: '' };

    if (!type) { row.reason = '类型未识别'; rows.push(row); return; }

    /* 一件事 = 主体 + 类型 + 标的物。标的是「哪一单」，不是「哪一类」：
       福建船政的 16 艘粮食船和 2+2 艘平台供应船是两件事，不该并成一条线。 */
    const sp = specOf(it.title, type);
    const key = sp ? (subj.n + '|' + type + '|' + sp.spec) : (subj.n + '|' + type + '|#' + it.id);
    row.key = key;
    row.stage = pickAct(type, it.title);
    rows.push(row);

    if (!map.has(key)) {
      map.set(key, { key, subj, type, cat: catOf(type, subj), items: [], stage: null });
    }
    const ev = map.get(key);
    ev.items.push(it);
    /* 报道按时间正序进来，最后一条带动作的就是这件事最近的进展。
       不比较「谁比谁靠后」——动作没有预设顺序。 */
    if (row.stage) ev.stage = row.stage;
  });

  const events = [...map.values()].map(ev => {
    ev.items.sort(sortByTime);
    const days = new Set(ev.items.map(i => i.d));
    ev.days = days.size;
    ev.first = ev.items[0];
    ev.last = ev.items[ev.items.length - 1];
    /* 进不进广场只看一条：这件事还有没有下一步。
       走完的留在详情里，但不占广场的位置。 */
    const endActs = END_ACT[ev.type] || [];
    ev.atEnd = !!(ev.stage && endActs.indexOf(ev.stage) >= 0);
    ev.pool = !ev.atEnd;
    ev.prio = prioOf(ev);
    ev.auth = authOf(ev);
    return ev;
  });

  events.forEach(ev => {
    ev.items.forEach(it => {
      const r = rows.find(x => x.it.id === it.id);
      if (r) r.inPool = ev.pool;
    });
  });

  return { rows, events };
}

