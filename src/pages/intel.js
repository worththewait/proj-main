/* ---------------- 日期浮窗定位（absolute 锚定 .ph-dwrap；右侧空间不足时改右对齐纠偏） ---------------- */
function openCalPop() {
  const pop = document.getElementById('calPop');
  if (!pop) return;
  // 页头入场动画未结束时打开浮窗会整体半透明，先落定动画
  const ph = pop.closest('.ph');
  if (ph) { ph.style.animation = 'none'; ph.style.opacity = '1'; ph.style.transform = 'none'; }
  pop.style.left = '0'; pop.style.right = 'auto';
  pop.classList.add('show');
  // 视口纠偏：右侧空间不足时改为左对齐，避免被窗口边缘裁掉
  const r = pop.getBoundingClientRect();
  if (r.right > window.innerWidth - 12) {
    pop.style.left = 'auto';
    pop.style.right = '0';
  }
}
