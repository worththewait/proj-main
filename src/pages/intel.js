/* 时间线记的是「进展」，不是「报道列表」。
   同一件事的同一个动作，常被多家媒体前后脚推送 —— 这些报道并成一个节点：
   主报道在该节点内按信源权威挑（同级取最新），节点时间跟着主报道走，其余作为跟报挂在节点下。
   认不出动作的报道不单独占位，并入它前面最近的那个节点。 */
/* 推到用户面前的那一条，取这件事里信源最权威的报道；
   同级按发布时间取最新的。同一件事被十几家转载时，看到的不是随手一家的版本。 */
function pickLead(items) {
  return items.slice().sort((a, b) =>
    (AUTH_PT[srcRank(b.src)] - AUTH_PT[srcRank(a.src)])
    || (b.d + b.hm).localeCompare(a.d + a.hm))[0];
}

function nodesOf(ev) {
  const out = [], byAct = new Map();
  ev.items.forEach(it => {
    const a = stageOf.get(it.id) || '';
    if (a && byAct.has(a)) { byAct.get(a).items.push(it); return; }
    if (!a && out.length) { out[out.length - 1].items.push(it); return; }
    const nd = { act: a, items: [it] };
    out.push(nd);
    if (a) byAct.set(a, nd);
  });
  /* 一个动作只亮一条主报道，其余进跟报；时间跟着主报道走 */
  out.forEach(nd => {
    nd.lead = pickLead(nd.items);
    nd.time = nd.lead.d + ' ' + nd.lead.hm;
  });
  return out;
}

/* 一件事最近一次进展的主报道：先取最后一个节点，再在节点内按权威挑 */
function latestLead(ev) {
  const nds = nodesOf(ev);
  return nds.length ? nds[nds.length - 1].lead : pickLead(ev.items);
}

