/* 时间线正文本身（不含卡片壳、不含筛选条）。
   单独拆出来是为了「关注 / 取关 / 换筛选」时只换这一块，
   不整页重建 —— 整页重绘会闪一下。 */
function tkFeedInner() {
  /* 一行 = 一件事，不是一条报道、也不是一个动作。
     同一件事的后续进展只更新这一行（动作、时间、报道条数变），
     不再另起一行重推一遍；要看全过程点进脉络。 */
  const list = TRACKS
    .filter(t => subjFilter === '全部' || t.subj === subjFilter)
    .slice()
    .sort((a, b) => b.lastTime.localeCompare(a.lastTime));

  if (!list.length) {
    return '<div class="intel-empty">还没有关注话题</div>';
  }

  /* 按「最近一次进展」的日期分组，一件事只落在它最新的那一天 */
  const groups = [];
  list.forEach(t => {
    const day = t.lastTime.slice(0, 5);
    let g = groups[groups.length - 1];
    if (!g || g.day !== day) { g = { day, items: [] }; groups.push(g); }
    g.items.push(t);
  });

  const html = groups.map((g, gi) => {
    const rows = g.items.map(t => {
      const ev = byKey.get(t.id);
      const isNew = !!(ev && ev.items.some(i => fetchedIds.has(i.id)));
      return '<div class="tk-row" data-thread="' + t.id + '">'
        + '<div class="lv-t">' + t.lastTime.slice(6) + '</div>'
        + '<div class="lv-spine"><i></i></div>'
        + '<div class="lv-c">'
        + '<div class="lv-tt"><span class="tk-sub">' + t.subj + '<i>' + t.type + '</i></span>'
        + (t.lastAct ? '<span class="tk-step">' + t.lastAct + '</span>' : '')
        + (isNew ? '<span class="tk-new">新</span>' : '')
        + '<a class="tk-rowunf" data-tunf="' + t.id + '">取消关注</a>'
        + '</div>'
        + '<div class="tk-title">' + t.lead.title + '</div>'
        + '<div class="tk-src">' + t.lead.src + origLink(t.lead.url, '查看原文 ↗')
        + '<span class="tk-n">共 ' + t.count + ' 条报道 · ' + t.nodeCount + ' 个进展</span>'
        + '</div>'
        + '</div></div>';
    }).join('');
    return '<div class="tk-day' + (gi === 0 ? ' first' : '') + (g.day === TODAY_MD ? ' today' : '') + '">' + dayLabel(g.day) + '</div>' + rows;
  }).join('');

  return html;
}

