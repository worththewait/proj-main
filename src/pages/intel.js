function origOf(it) {
  if (!it) return '';
  const u = it.url || ORIG[it.id];
  if (u) return u;
  if (!it.title) return '';
  return 'https://cn.bing.com/search?q=' + encodeURIComponent((it.src || '') + ' ' + it.title);
}

