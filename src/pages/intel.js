/* ---------------- 话题广场 ----------------
   一批 6 条，底部「换一换」翻下一批，翻到底回第一批 —— 不往下拉长。
   候选都来自最近 5 天的报道（输入层已过滤），这里只再按三项排队决定谁上：
     ① 档位：安全 > 政策 > 订单 > 建造交付 > 加注 > 行情 > 企业
     ② 信源权威：同档里先给证据硬的（官方 > 权威机构与学术 > 行业垂媒 > 自媒体）
     ③ 时效：还分不出来，就新的事在前
     ④ 同批同类限 4 条：只按分数排，一批很快被一类事占满（实测 10 条都是签约），
        超出的让给后面的事，落到下一批 —— 一类事不刷屏
   前三项合起来算一个分，档位权重最大，权威和时效只在同档内部搬动顺序。
   一条事件线一行，关注落的也是这条线。关注了就从榜上撤走 —— 它已经进了下方
   时间线，不再在这儿占一个位置；空出的位置由下一名补上，所以榜单始终是满的。
   要退回，在时间线那一行点「取消关注」，这条会重新回到广场候选。 */
const PLAZA_SIZE = 6;
const CAP_PER_TYPE = 4;
let plazaPage = 0;

/* 把候选切成批：每轮按分数往下取，同类取满 4 条就跳过，取满 6 条成一批，
   剩下的继续切下一批。 */
function plazaBatches() {
  const rest = MODEL.events
    /* 准入两条：
       ① 还没走到终点 —— 走完的留在详情里，不占广场的位置；
       ② 还没被关注 —— 关注了的事只活在时间线里，不在广场再出现一次。
       时效不在这里判 —— 窗口外的报道根本没进 MODEL。 */
    .filter(e => !e.atEnd && !follows.has(e.key))
    .sort((a, b) => scoreOf(b) - scoreOf(a)
      || (b.last.d + b.last.hm).localeCompare(a.last.d + a.last.hm));

  const out = [];
  while (rest.length) {
    const quota = {};
    const batch = [];
    for (let i = 0; i < rest.length && batch.length < PLAZA_SIZE; i++) {
      const e = rest[i];
      const used = quota[e.type] || 0;
      if (used >= CAP_PER_TYPE) continue;
      quota[e.type] = used + 1;
      batch.push(e);
      rest.splice(i, 1);
      i--;
    }
    if (!batch.length) break;
    out.push(batch);
  }
  /* 末批只剩一两条，并进上一批 —— 免得翻到最后是一页几乎空着的列表 */
  if (out.length > 1 && out[out.length - 1].length < 3) {
    out[out.length - 2] = out[out.length - 2].concat(out.pop());
  }
  return out;
}

function plazaBody() {
  /* 广场只放还没关注的事。关注之后它从广场撤走，只在下方时间线里以一行存在 ——
     同一件事不在页面上出现两遍。 */
  const batches = plazaBatches();
  if (!batches.length) {
    return '<div class="intel-empty">候选都已关注，进展见下方时间线</div>';
  }
  if (plazaPage >= batches.length) plazaPage = 0;
  const list = batches[plazaPage];

  /* 两列：左侧「主体·类型 + 标题」，右侧竖排「阶段标签」与「日期 + 关注」，
     标签在上、日期与关注在下，行高按两条文字对齐。 */
  const rows = '<div class="pl-grid">' + list.map(e => {
    /* 广场也是「一件事一条」：标题取最近一次进展的主报道 */
    const lead = latestLead(e);
    return '<article class="pl-card">'
      + '<span class="pl-subj"><b>' + e.subj.n + '</b><i>' + e.type + '</i></span>'
      + '<button type="button" class="pl-tt" data-plzadetail="' + e.key + '">' + lead.title + '</button>'
      + '<div class="pl-side">'
      + (e.stage ? '<span class="tk-step">' + e.stage + '</span>' : '<span class="tk-step ph"></span>')
      + '<div class="pl-ops"><span class="pl-d">' + lead.d + '</span>'
      + '<button type="button" class="pl-follow" data-plzafollow="' + e.key + '">'
      + '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 5v14M5 12h14"/></svg>关注</button></div>'
      + '</div>'
      + '</article>';
  }).join('') + '</div>';

  const fold = batches.length > 1
    ? '<div class="pl-more"><button type="button" id="btnPlzMore">换一换</button></div>'
    : '';

  return rows + fold;
}

