function viewThreadDetail() {
  const t = detailTrack;
  const ev = byKey.get(t.id);
  const on = follows.has(t.id);
  const start = t.timeline[t.timeline.length - 1].time.slice(0, 5);
  /* 头部标的是「这件事最开始是什么动作」，不是最新动作 ——
     写最新动作配「10-27 起」会读成 10-27 发生的是遇袭。 */
  const firstAct = (t.timeline.slice().reverse().find(n => n.act) || {}).act;

  /* 每条报道标它自己的动作；蓝点只打在「动作是这条线上第一次出现」的节点上。
     脉络按时间正序读：从这事怎么起的一路看到现在。 */
  /* 一个节点 = 一次进展；同一动作的多家报道折在节点下面，点开才看得到 */
  const tl = t.timeline.slice().reverse().map(n => {
    const more = (n.more && n.more.length)
      ? '<div class="dt-tl-more">另有 ' + n.more.length + ' 家报道：'
          + n.more.map(x => x.src + ' ' + x.time + origLink(x.url, '原文 ↗')).join('　') + '</div>'
      : '';
    return '<div class="dt-tl-item' + (n.stage ? ' adv' : '') + '">'
      + '<span class="dt-tl-dot"></span>'
      + '<div class="dt-tl-time">' + n.time
      + (n.act ? '<span class="dt-tl-st">' + n.act + '</span>' : '') + '</div>'
      + '<div class="dt-tl-text">' + n.text
      + '<span class="sc">来源：' + n.src + origLink(n.url, '查看原文 ↗') + '</span>' + more + '</div>'
      + '</div>';
  }).join('');

  return '<div class="doc doc-read">'
    + '<div class="dt-bar">'
    + '<button class="intel-back" id="btnBack">← 返回</button>'
    + '<button class="intel-page-btn" id="btnUnfollow">' + (on ? '取消关注' : '关注') + '</button>'
    + '</div>'
    + '<div class="dt-card">'
    + '<div class="dt-title" role="heading" aria-level="1">' + t.subj
    + '<span class="dt-ty">' + t.type + '</span></div>'
    + '<div class="dt-meta">'
    + (firstAct ? '<span class="st">' + firstAct + '</span><span class="sep">·</span>' : '')
    + '<span>' + start + ' 起</span><span class="sep">·</span><span>' + t.count + ' 条报道</span></div>'
    + '<div class="dt-tl">' + tl + '</div>'
    + '</div></div>';
}

