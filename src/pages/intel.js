function origLink(url, label) {
  if (!url) return '';
  const href = url.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
  return '<a class="orig-a" href="' + href + '" target="_blank" rel="noopener noreferrer"'
    + ' data-orig>' + (label || '查看原文') + '</a>';
}

