/* ---------------- 7×24 右栏快讯 ---------------- */
function liveRail() {
  /* 7×24 是一条连续时间流：选中日期与前两日接在一起，按「日 + 时分」倒序排，
     不依赖数据数组本身的书写顺序。当日只写时分，往日写完整年月日，日期不另起分隔。 */
  const keys = liveDays(selDate);
  const list = keys.reduce((acc, k) => acc.concat(LIVE.filter(x => x.day === k)), []);
  list.sort((a, b) => (b.day + ' ' + b.time).localeCompare(a.day + ' ' + a.time));

  const todayKey = dayKey(selDate);
  const stamp = it => (it.day === todayKey ? it.time : selDate.y + '-' + it.day + ' ' + it.time);
  const rows = list.length ? list.map(it =>
    '<div class="rl-row' + (freshLive.has(it.id) ? ' fresh' : '') + '" data-live="' + it.id + '">'
      + '<span class="rl-t">' + stamp(it) + '</span>'
      + '<span class="rl-tt">' + it.title + '</span></div>').join('')
    : '<div class="rl-empty">近日暂无实时情报</div>';

  return '<aside class="daily-side">'
    + '<div class="col-head"><span class="live-dot"></span><span class="ct">7×24 实时</span></div>'
    + '<div class="rl-wrap"><div class="rl-body">' + rows + '</div>'
    + '<div class="rl-end">已全部加载</div></div>'
    + '</aside>';
}

