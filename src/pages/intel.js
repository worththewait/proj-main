function srcRank(src) { return SRC_RANK[src] || 'B'; }

/* 一件事的权威度取它所有报道里最高的那一级：
   被新华社报过的事，就该比只有一家公众号报过的高看一眼。 */
function authOf(ev) {
  return ev.items.reduce((m, it) => Math.max(m, AUTH_PT[srcRank(it.src)]), 0);
}

/* 距今几天：md 形如 '10-23'，基准日当天为 0。
   基准日 BASE_D 在情报流之后才定 —— 原型是抽样数据，对齐最新一条报道；
   真实环境把它换成当天。 */
function dayDiff(md, base) {
  const p = md.split('-').map(Number);
  const q = base.split('-').map(Number);
  const a = Date.UTC(2026, q[0] - 1, q[1]);
  const b = Date.UTC(2026, p[0] - 1, p[1]);
  return Math.round((a - b) / 86400000);
}

function daysAgo(md) { return dayDiff(md, BASE_D); }

/* 输入窗口：只取最近 5 天发布的报道进入跟踪，更早的不进来。
   这是输入层的范围，不是事后再去算「多久没更新」——
   新闻本身就在窗口外，就不该参与抽取、聚合、打分，也不该出现在广场上。
   窗口外的报道仍留在早报与 7×24 里，只是不构成跟踪的事。 */
const WINDOW_DAYS = 5;

/* 排队分 = 档位 + 信源权威 + 时效。
   档位一档差 100 分，权威最多 30 分、时效最多 9 分 ——
   权威只能在同一个档位里搬动顺序，翻不了档，安全永远在第一档。 */
const FRESH_MAX = 9;

function scoreOf(ev) {
  const d = daysAgo(ev.last.d);
  return (9 - ev.prio) * 100 + ev.auth * 10 + Math.max(0, FRESH_MAX - d);
}

