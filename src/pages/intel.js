function renderCal() {
  const first = new Date(calYear, calMonth - 1, 1);
  const startDow = first.getDay();
  const days = new Date(calYear, calMonth, 0).getDate();
  let cells = '';
  for (let i = 0; i < startDow; i++) cells += '<span class="day empty"></span>';
  for (let d = 1; d <= days; d++) {
    const sel = (calYear === selDate.y && calMonth === selDate.m && d === selDate.d);
    const has = calYear === TODAY.y && !!EARLY_BY_DAY[pad2(calMonth) + '-' + pad2(d)];
    cells += '<span class="day' + (sel ? ' sel' : '') + (has ? ' has' : '') + '" data-day="' + d + '">' + d + '</span>';
  }
  document.getElementById('calDays').innerHTML = cells;
  document.getElementById('calYM').textContent = calYear + '年' + pad2(calMonth) + '月';
  document.querySelectorAll('#calDays .day[data-day]').forEach(el => {
    el.onclick = () => {
      selDate = { y: calYear, m: calMonth, d: +el.dataset.day };
      document.getElementById('calPop').classList.remove('show');
      pageScroll = 0;
      render();
    };
  });
}

