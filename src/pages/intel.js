/* ---------------- 每日更新 ----------------
   关注不是把一条线钉在页面上，而是把它加进定向检索队列。
   每天 09:00 跑一轮：全量情报流照跑，同时按关注的主体再检一遍，
   抓到的新稿并入情报流，属于已关注的事就在时间线上多一个节点。

   这是默认在后台跑的任务，页面上不给按钮、也不做手动触发。
   原型没法真等到明早九点，用「进页面时补跑」模拟：今天 09:00 已过、
   这一天还没跑过，就把队列里的稿一次并进来。 */
const RUN_HOUR = 9;
const fetchedIds = new Set();    /* 这一轮抓进来的，时间线上标「新」 */
const runDone = new Set();       /* 哪天的那一轮已经跑过 */

const pad0 = n => (n < 10 ? '0' : '') + n;
const ymd = d => d.getFullYear() + '-' + pad0(d.getMonth() + 1) + '-' + pad0(d.getDate());

/* 调度只在后台跑，界面上不留任何痕迹 —— 状态条、上次跑的时间、几条线，
   都是内部执行细节，用户看的是「这件事有没有新进展」，不是「任务跑没跑」。 */

/* 到点就跑：一天一轮，队列里的稿一次全并进来。
   入库后走整条链重建（新稿可能并线、也可能让某条线归档）。 */
function autoRun() {
  const now = new Date();
  if (now.getHours() < RUN_HOUR) return;      /* 今天还没到九点 */
  const key = ymd(now);
  if (runDone.has(key)) return;               /* 今天这一轮跑过了 */
  runDone.add(key);
  if (!PENDING.length) return;
  while (PENDING.length) {
    const it = PENDING.shift();
    ITEMS.push(it);
    LIVE.push(Object.assign({}, it, { id: 'lv-' + it.id, day: it.d, time: it.hm }));
    fetchedIds.add(it.id);
  }
  rebuild();
}

