/* 一件事的标的物：认得出是「哪一单」，两条报道才并成一件事。
   只做合并键，不上界面 —— 它是从标题里切出来的片段（「2 艘成品油轮」「广荣」），
   读者看标题就够了，把这些碎片摆到列表里只是噪音。
   认不出就返回 null，这条单列 —— 宁可把一件事拆成两条，
   也不可把两件事糊成一件，糊了用户会对进展判断失去信任。 */
function specOf(title, type) {
  let m = title.match(/[“"]([^”"]{2,24})[”"]/);
  if (m) return { spec: 'n:' + m[1], label: m[1] };

  m = title.match(/《([^》]{2,30})》/);
  if (m) return { spec: 'f:' + m[1], label: m[1] };

  /* 几艘：数量就是这一单的标识。船型只进名字，不进 key ——
     同一单在签约稿和采购稿里写法不同（「16 艘粮食船」/「16 艘粮食船主机」），
     用船型会把它们劈成两条。 */
  m = title.match(/(\d+(?:\s*\+\s*\d+)?)\s*艘/);
  if (m) {
    const n = m[1].replace(/\s/g, '');
    /* 船型取「N 艘」之后紧跟的那个「……船」。取全文最后一个会把
       「在大连船」「中国船」这类词尾抓进来，标的就成了「4 艘亿元在大连船」。 */
    const rest = title.slice(m.index + m[0].length, m.index + m[0].length + 24);
    const kw = rest.match(/[\u4e00-\u9fa5]{1,8}(?:船|轮)/) || [];
    let k = kw.length ? kw[0] : '';
    k = k.replace(/^(载重吨|万立方米|立方米|万吨级|吨级|[吨万千百十艘])+/, '');  /* 削掉粘在前面的吨位/容积单位 */
    const pc = k.indexOf('船');
    if (pc > 0) k = k.slice(0, pc + 1);             /* 「散货船首制船」只取到第一个「船」 */
    if (k.length < 2) k = '';
    return { spec: 'q:' + n, label: n + ' 艘' + k };
  }

  /* 事故没有标的物，靠「同一主体 + 同一类型」归拢，用固定值 */
  if (type === '事故') return { spec: 'x', label: '' };

  return null;
}

/* 广场排序：按「多晚知道代价最大」分档，同档按时间倒序。
   优先级只决定顺序，不决定准不准进。 */
/* 广场分档：按「多晚知道代价最大」排。
   事故不可逆；政策一落地就没了窗口；订单排的是船位和交期，晚一周报价和位子都变了；
   建造节点延误直接影响后面整条船；加注是服务性业务，晚知道只影响一次采购；
   行情看趋势，企业变动基本是既成事实。 */
function prioOf(ev) {
  const t = ev.type;
  if (t === '事故') {
    const s = ev.items.map(i => i.title).join('');
    return /死|遇难|失联|沉没|溢油|泄漏|劫持|爆炸|闪爆/.test(s) ? 1 : 2;
  }
  if (t === '政策') return 3;
  if (t === '订单') return 4;
  if (t === '建造' || t === '交付') return 5;
  if (t === '加注') return 6;
  if (t === '市场') return 7;
  return 8;
}

