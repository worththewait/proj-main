/* 「船舶」这类弱尾词后面跟事故词或动作词时，是普通名词不是机构名
   （贵港通报船舶闪爆）。「船厂」「重工」这类强尾词不受此限。 */
const SOFT_TAIL = ['船舶', '船业', '船燃', '能源', '集团', '国际', '电力'];
const NOT_ORG = /闪爆|爆炸|起火|事故|失联|遇难|伤亡|沉没|碰撞|泄漏|交付|下水|签约|订单/;
const BAD_NAME = /闪爆|爆炸|起火|事故|失联|遇难|伤亡|沉没|碰撞|泄漏|订单|签约|签署|交付|开工|下水|揭牌|成立$/;
/* 截断时不能停在词中间（「贵港闪爆事故」退到「贵港闪」仍不成词），单字也一并挡掉 */
const BAD_CHAR = /[爆火故沉撞泄漏伤亡死遇失闪]/;
const COUNTRY = /^(印度|希腊|英国|美国|日本|韩国|挪威|德国|法国|丹麦|新加坡|越南|菲律宾|意大利|西班牙|荷兰|比利时|土耳其|阿联酋|沙特|巴西|加拿大|澳大利亚|中国)$/;
const NAME_BREAK = /[向与同在对为的和据已将再又，。、：；（）()\s]/;

function cleanName(v) {
  return v.replace(/(锚地|锚区|港区|码头|附近|水域)$/, '').trim();
}
function okName(v) {
  if (!v) return false;
  return v.length >= 2 && v.length <= 16 && !COUNTRY.test(v) && !BAD_NAME.test(v) && !BAD_CHAR.test(v);
}
/* 量词贪婪会把「长宏国际交付」整段吞进来：先剥掉结尾动作词，
   再从长到短取第一个可用的前缀 —— 「贵港闪爆事故」会一路退到「贵港」。 */
function trimToOk(v) {
  v = cleanName(v).replace(/(交付|开工|下水|签署|签约|揭牌|成立|加注|完成|实现|举行|召开|宣布|发布|确认|证实|获|接获|中标)$/, '');
  for (let n = v.length; n >= 2; n--) {
    const s = cleanName(v.slice(0, n));
    if (okName(s)) return s;
  }
  return null;
}

function guessSubject(title) {
  let m, v;

  /* ① 下单方在前：A 向/与 B 订造 —— 主体是 A，B 是承建方 */
  m = title.match(/^(.{2,24}?)(?:据报)?(?:再次|首次|再|又)?(?:向|与|同)(.{2,24}?)(?:订造|订购|下单|签署|签订|签约|采购|增订|交付|命名)/);
  if (m) {
    v = m[1].trim();
    /* 「希腊 Alpha Gas 首次转向中国船厂，在恒力重工订造」这类，前缀是国名与动作，主体是中间的英文名 */
    const en = v.match(/[A-Za-z][A-Za-z&.\-]*(?:\s+[A-Za-z&.\-]+)+/);
    if (/^[\u4e00-\u9fa5]+\s/.test(v) && en) v = en[0].trim();
    if (okName(v)) return v;
  }

  /* ② 承建方在前：A 获/接获 B 订单 —— 主体是 A */
  m = title.match(/^(.{2,20}?)(?:据报)?(?:获|接获|赢得|中标)/);
  if (m && okName(v = m[1].trim())) return v;

  /* ③ 组织名：取最靠左的「专名 + 尾词」 */
  let hit = null;
  ORG_TAIL.forEach(w => {
    let i = -1;
    while ((i = title.indexOf(w, i + 1)) >= 0) {
      if (SOFT_TAIL.indexOf(w) >= 0 && NOT_ORG.test(title.slice(i + w.length, i + w.length + 3))) continue;
      let st = i;
      while (st > 0 && i - st < 6 && !NAME_BREAK.test(title[st - 1])) st--;
      const name = title.slice(st, i + w.length);
      if (name.length >= w.length + 2 && (!hit || st < hit.at)) hit = { name, at: st };
    }
  });
  if (hit && okName(v = cleanName(hit.name))) return v;

  /* ④ 开头专名：2—6 字，后面紧跟空格、数字或动作词 —— 新闻标题的主体多在句首 */
  m = title.match(/^([\u4e00-\u9fa5]{2,6})(?=\s|\d|证实|确认|完成|实现|举行|召开|宣布|发布|签署|签约|交付|开工|揭牌|成立|加注|扩至|增至|自有|已|将|拟|再|又|与|和|向|被|获|通报)/);
  if (m && (v = trimToOk(m[1]))) return v;

  /* ⑤ 地名机构：以行政区划或港口结尾 */
  m = title.match(/^([\u4e00-\u9fa5]{2,5}[港市省县区局厂])/);
  if (m && (v = trimToOk(m[1]))) return v;

  /* ⑥ 英文专名，排除全大写缩写 */
  m = title.match(/[A-Z][A-Za-z&.\-]{1,}(?:\s+[A-Z][A-Za-z&.\-]{1,}){0,2}/);
  if (m && okName(v = m[0]) && !/^(TEU|VLGC|LNG|LPG|PCTC|IMO|HVS|CEO|COO|ESG)$/.test(m[0])) return v;

  return null;
}

function pickSubject(text) {
  let best = null;
  SUBJECTS.forEach(s => {
    s.a.forEach(al => {
      const i = text.indexOf(al);
      if (i >= 0 && (!best || i < best.i)) best = { s, i };
    });
  });
  if (best) return best.s;

  /* 库里没有不等于没有主体：现抽一个，标 temp，单列不进别人的线 */
  const g = guessSubject(text);
  if (!g) return null;
  return { n: g, label: g, role: '其他', a: [g], temp: true };
}

function pickType(it) {
  for (const r of TYPE_RULES) if (r.w.some(w => it.title.includes(w))) return r.t;
  for (const r of TYPE_RULES) if (r.w.some(w => (it.title + it.summary).includes(w))) return r.t;
  return null;
}

/* 一篇报道认出来的动作；多个词命中时取位置最靠后的那个。
   只看标题，不看摘要：摘要里几乎每篇都写「预计 2027 年交付」，
   拿它判动作会把在做的单子一律判成交付、直接归档。 */
function pickAct(type, title) {
  const rules = ACT_BY_TYPE[type];
  if (!rules) return null;
  let best = null, at = -1;
  rules.forEach(r => r[1].forEach(w => {
    const i = title.lastIndexOf(w);
    if (i > at) { at = i; best = r[0]; }
  }));
  return best;
}

function catOf(type, subj) {
  if (type === '事故') return '安全与事故';
  if (type === '政策') return '政策与规则';
  if (type === '企业') return '企业与资本';
  if (type === '市场') return '市场指数';
  if (type === '加注') return '船型与燃料';
  return (subj.role === '船东' || subj.role === '货主') ? '船东与货主' : '船厂与配套';
}

