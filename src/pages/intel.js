/* 一条事件线 → 时间线上的一串节点。
   一个节点 = 一次真实进展（一个动作），不是一个来源一次推送。
   同一动作被多家报道时，节点只留最早那条做正文，其余挂在 more 里当跟报。 */
function toTrack(ev) {
  const nodes = nodesOf(ev);
  const lastNd = nodes[nodes.length - 1] || null;
  /* 行上展示的是「这件事现在到哪一步」：取最近一次进展；
     这一次进展若被多家报道，再按信源权威挑一条主报道。
     不能拿整件事里最权威的旧稿当标题 —— 那会出现
     「11-02 复航」却配 10-29「被击中」的标题。 */
  const lead = lastNd ? lastNd.lead : pickLead(ev.items);
  return {
    id: ev.key,
    subj: ev.subj.n,                    /* 主体名，时间线上挂这个 */
    type: ev.type,                      /* 类型：订单、建造、事故……跟主体同行显示 */
    cat: ev.cat,
    days: ev.days,
    count: ev.items.length,
    nodeCount: nodes.length,
    day: ev.last.d,
    /* 这一行代表「这件事现在到哪一步了」：时间、动作都取最近一次进展 */
    lastTime: lastNd ? lastNd.time : (ev.last.d + ' ' + ev.last.hm),
    lastAct: lastNd ? (lastNd.act || '') : '',
    /* 行上展示的那条报道：最权威来源，不是最新一条 */
    lead: { title: lead.title, src: lead.src, time: lead.d + ' ' + lead.hm, url: origOf(lead) },
    isNew: false,
    timeline: nodes.slice().reverse().map(nd => ({
      id: nd.lead.id,
      time: nd.time,
      text: nd.lead.title,
      src: nd.items.length > 1 ? nd.lead.src + ' 等 ' + nd.items.length + ' 家' : nd.lead.src,
      url: origOf(nd.lead),
      act: nd.act,
      stage: nd.act,
      more: nd.items.filter(x => x.id !== nd.lead.id).map(x => ({
        src: x.src, time: x.d + ' ' + x.hm, url: origOf(x), text: x.title
      }))
    }))
  };
}

/* 关注哪些事件线，时间线就挂哪些线的节点。
   关注是一条线，不是这家公司：同公司后来另起一件事，是另一条线，另关注一次。 */
function syncTracks() {
  TRACKS = MODEL.events
    .filter(ev => follows.has(ev.key))
    .map(toTrack)
    .sort((a, b) => b.day.localeCompare(a.day));
}

function unfollowTrack(key) {
  follows.delete(key);
  syncTracks();
}

